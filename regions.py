def _norm(s: str) -> str:
    s = (s or "").strip()
    s = s.replace("״", '"').replace("׳", "'").replace("ג'", "ג").replace("ח'", "ח")
    s = s.replace("ע'", "ע").replace("ז'", "ז").replace("ת'", "ת")
    s = re.sub(r"['\"`.]", "", s)
    s = re.sub(r"[-–—/\\,()]+", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    s = s.replace("קריית", "קרית").replace("קרית ", "קרית ")
    for pre in ("קיבוץ ", "מושב ", "ישוב ", "יישוב ", "כפר הנוער ", "מצפה ", "ק ", "ק. "):
        if s.startswith(pre) and s[len(pre):] in _CITY_TO_REGION:
            s = s[len(pre):]
    return s


