def city_region(city: str) -> str:
    """מפתח האזור של עיר כפי שהיא כתובה בפריוריטי."""
    n = _norm(city)
    if not n:
        return "none"
    r = _CITY_TO_REGION.get(n)
    if r:
        return r
    for pre, reg in _PREFIX:
        if n.startswith(pre):
            return reg
    return "unknown"


def group_cities(agg: dict, rank: str = "s") -> dict:
    """תשובת bi_range_dim עם p_dim='city' -> אותה צורה, שורה לכל אזור.
    לכל אזור גם רשימת הערים שלו (cities), בשביל הצלילה במסך."""
    rows = {k: {"k": k, "s": 0, "p": 0, "q": 0, "c": 0, "n": 0, "cities": []} for k, _ in REGIONS}
    for g in agg.get("rows") or []:
        reg = city_region(g.get("k") or "")
        r = rows[reg]
        for f in ("s", "p", "q", "c", "n"):
            r[f] += g.get(f) or 0
        r["cities"].append(g)
    rest = agg.get("rest")
    if isinstance(rest, dict) and rest.get("cnt"):
        # ערים מעבר לתקרת השליפה — נכנסות ל"לא מזוהה" בלי פירוט
        r = rows["unknown"]
        for f in ("s", "p", "q"):
            r[f] += rest.get(f) or 0
        r["rest_cnt"] = rest.get("cnt")
    out = []
    for k, _ in REGIONS:
        r = rows[k]
        if not r["cities"] and not r.get("rest_cnt"):
            continue
        key = "q" if rank == "q" else "s"
        r["cities"].sort(key=lambda g: -(g.get(key) or 0))
        r["lbl"] = REGION_NAME[k]
        out.append(r)
    tail = {"unknown", "none"}
    out.sort(key=lambda r: (r["k"] in tail, -(r["q"] if rank == "q" else r["s"])))
    return {"total_s": agg.get("total_s") or 0, "total_q": agg.get("total_q") or 0,
            "total_p": agg.get("total_p") or 0, "orders": agg.get("orders") or 0,
            "customers": agg.get("customers") or 0, "qcov": agg.get("qcov"),
            "rest": None, "rows": out}
